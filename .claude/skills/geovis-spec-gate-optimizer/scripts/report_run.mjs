#!/usr/bin/env node
/**
 * Writes `eval-report.json` and `SUMMARY.md` of a run from its artifacts only:
 * `cases/*.score.json` (from `score_case.mjs`) and, once a person has
 * classified the run, `classification.json`. Never edit either output by hand:
 * change the inputs and run it again.
 *
 *   node report_run.mjs <run-dir>
 *
 * `classification.json` records the classification decision:
 *
 *   { "decision": "<url>", "groups": [{ "cases": ["golden-ivs"], "class": "rejected",
 *     "scope": "transform", "layer": "server legend", "issue": 115, "note": "...",
 *     "declined": false }] }
 *
 * A passing case no group names is `approved`; a failing one is `unclassified`
 * and gets no proposal until a group names it. Issue proposals are the
 * non-approved, non-declined groups, one per `scope`, each carrying the issues
 * that already cover it; a scope with no issue is `new`, to be confirmed.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import process from 'node:process';

const SCOPES = ['catalogue', 'intent', 'data', 'transform', 'agent-instructions', 'validation', 'render', 'evals-gate', 'skill'];
const CLASSES = ['approved', 'rejected', 'inconclusive'];

const runDir = process.argv[2];
if (!runDir) {
  process.stderr.write('usage: report_run.mjs <run-dir>\n');
  process.exit(1);
}
const runId = basename(resolve(runDir));
const read = (path) => { return JSON.parse(readFileSync(path, 'utf8')) };

const casesDir = join(runDir, 'cases');
const scores = existsSync(casesDir)
  ? readdirSync(casesDir).filter((f) => { return f.endsWith('.score.json') }).sort().map((f) => { return read(join(casesDir, f)) })
  : [];

const classificationFile = join(runDir, 'classification.json');
const classification = existsSync(classificationFile) ? read(classificationFile) : { decision: null, groups: [] };
const known = new Set(scores.map((s) => { return s.case }));
for (const group of classification.groups) {
  if (!CLASSES.includes(group.class)) throw new Error(`classification: unknown class ${group.class}`);
  if (group.class !== 'approved' && !SCOPES.includes(group.scope)) throw new Error(`classification: unknown scope ${group.scope}`);
  for (const id of group.cases) if (!known.has(id)) throw new Error(`classification: no score for case ${id}`);
}
const groupOf = (id) => { return classification.groups.find((g) => { return g.cases.includes(id) }) };

const cases = scores.map((s) => {
  const group = groupOf(s.case);
  return {
    case: s.case,
    prompt: s.prompt,
    httpStatus: s.httpStatus,
    durationMs: s.durationMs,
    outcome: s.outcome,
    issues: s.issues,
    failedChecks: s.checks.filter((c) => { return !c.passed }).map((c) => { return `${c.id}: ${c.note}` }),
    passed: s.passed,
    class: group?.class ?? (s.passed ? 'approved' : 'unclassified'),
    scope: group?.scope ?? null,
    issue: group?.issue ?? null,
  };
});

const open = classification.groups.filter((g) => { return g.class !== 'approved' && !g.declined });
const proposals = SCOPES.flatMap((scope) => {
  const groups = open.filter((g) => { return g.scope === scope });
  if (groups.length === 0) return [];
  const caseIds = groups.flatMap((g) => { return g.cases });
  return [{
    scope,
    status: groups.every((g) => { return g.issue }) ? 'linked' : 'new',
    issues: [...new Set(groups.map((g) => { return g.issue }).filter(Boolean))],
    layer: [...new Set(groups.map((g) => { return g.layer }).filter(Boolean))].join('; ') || null,
    cases: caseIds,
    rationale: [
      `run ${runId}`,
      ...caseIds.map((id) => { const c = cases.find((x) => { return x.case === id }); return `${id}: ${c.failedChecks.join(', ') || 'passed'}` }),
      ...groups.map((g) => { return g.note }).filter(Boolean),
    ],
  }];
});

const passed = cases.filter((c) => { return c.passed }).length;
const report = {
  runId,
  decision: classification.decision,
  totals: { cases: cases.length, passed, failed: cases.length - passed },
  cases,
  declined: classification.groups.filter((g) => { return g.declined }),
  proposals,
};
writeFileSync(join(runDir, 'eval-report.json'), `${JSON.stringify(report, null, 2)}\n`);

const code = (s) => { return `\`${s}\`` };
const issueRef = (n) => { return n ? `#${n}` : '' };
const lines = [
  `# Eval run ${runId}`,
  '',
  `Generated by ${code('scripts/report_run.mjs')} from ${code('cases/*.score.json')}${classification.decision ? ` and the classification decision ${classification.decision}` : ''}; do not edit.`,
  '',
  `${passed} of ${cases.length} cases pass.`,
  '',
  '| Case | HTTP | Outcome | Passed | Class | Scope | Issue |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...cases.map((c) => { return `| ${code(c.case)} | ${c.httpStatus} | ${c.outcome} | ${c.passed ? 'yes' : 'no'} | ${c.class} | ${c.scope ?? ''} | ${issueRef(c.issue)} |` }),
  '',
  '## Issue proposals by scope',
  '',
  ...(proposals.length === 0
    ? ['None.']
    : [
      '| Scope | Status | Issues | Layer | Cases |',
      '| --- | --- | --- | --- | --- |',
      ...proposals.map((p) => { return `| ${p.scope} | ${p.status} | ${p.issues.map(issueRef).join(', ')} | ${p.layer ?? ''} | ${p.cases.map(code).join(', ')} |` }),
    ]),
];
const declined = report.declined.map((g) => { return `- ${g.scope}: ${g.note ?? ''} (declined)` });
if (declined.length > 0) lines.push('', '## Declined', '', ...declined);
const unclassified = cases.filter((c) => { return c.class === 'unclassified' }).map((c) => { return `- ${code(c.case)}: ${c.failedChecks.join(', ')}` });
if (unclassified.length > 0) lines.push('', '## Awaiting classification', '', ...unclassified);
writeFileSync(join(runDir, 'SUMMARY.md'), `${lines.join('\n')}\n`);

process.stdout.write(`report: ${passed}/${cases.length} pass, ${proposals.length} proposal(s), ${unclassified.length} unclassified\n`);
